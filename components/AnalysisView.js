/* Renders the structured Gemini analysis (React escapes all text = XSS safe) */
import { UrgencyBadge } from "./Badges";

const DEFAULT_DISCLAIMER =
  "These AI suggestions are preliminary and do not replace a professional diagnosis by a qualified mechanic.";

export default function AnalysisView({ analysis }) {
  if (!analysis) return <div className="ai-empty">No AI analysis available for this request.</div>;
  const causes = analysis.possibleCauses || [];
  const steps = analysis.troubleshootingSteps || [];
  return (
    <div className="ai-result">
      <div className="ai-result-head">
        <h4>AI Preliminary Analysis</h4>
        <UrgencyBadge urgency={analysis.urgency} />
      </div>
      {analysis.summary && <p className="ai-summary">{analysis.summary}</p>}
      {analysis.safetyWarning && (
        <div className="safety-warning"><strong>Safety:</strong> {analysis.safetyWarning}</div>
      )}
      <div className="ai-grid">
        <div className="ai-block">
          <h5>Possible Causes</h5>
          <ul className="cause-list">
            {causes.length ? causes.map((c, i) => (
              <li key={i}>
                <span className="cause-name">{c.cause}</span>
                <span className={`likelihood likelihood-${(c.likelihood || "").toLowerCase()}`}>{c.likelihood}</span>
                {c.explanation && <p className="cause-exp">{c.explanation}</p>}
              </li>
            )) : <li>Not available</li>}
          </ul>
        </div>
        <div className="ai-block">
          <h5>Preliminary Troubleshooting Steps</h5>
          <ol className="step-list">
            {steps.length ? steps.map((s, i) => <li key={i}>{s}</li>) : <li>Not available</li>}
          </ol>
        </div>
      </div>
      <div className={`inspection ${analysis.inspectionRequired ? "inspection-yes" : "inspection-no"}`}>
        <strong>{analysis.inspectionRequired ? "Professional inspection recommended." : "Inspection may not be immediately required."}</strong>{" "}
        {analysis.inspectionReason}
      </div>
      {analysis.estimatedServiceType && (
        <p className="ai-meta"><strong>Likely service type:</strong> {analysis.estimatedServiceType}</p>
      )}
      <p className="ai-disclaimer">⚠ {analysis.disclaimer || DEFAULT_DISCLAIMER}</p>
      {analysis.model && <p className="ai-model">Generated by {analysis.model}</p>}
    </div>
  );
}
